#!/usr/bin/env python3
"""Generate the original Ember pixel frames and epet species, without external artwork."""
from pathlib import Path


def frame(pose):
    """Return one 32x32 indexed frame; palette zero remains transparent."""
    pixels = [[0] * 32 for _ in range(32)]
    for y in range(4, 28):
        for x in range(3, 29):
            if ((x - 15.5) / 13) ** 2 + ((y - 16) / 12) ** 2 <= 1:
                pixels[y][x] = 2
    if pose == 'happy':
        for x, y in [(4, 4), (25, 3), (28, 8)]:
            pixels[y][x] = 5
    for y in range(32):
        for x in range(32):
            if pixels[y][x] == 2 and any(not (0 <= x + dx < 32 and 0 <= y + dy < 32) or pixels[y + dy][x + dx] == 0 for dx, dy in [(1, 0), (-1, 0), (0, 1), (0, -1)]):
                pixels[y][x] = 1
            elif pixels[y][x] == 2 and y > 22:
                pixels[y][x] = 3
    for x in [8, 22]:
        for y in [27, 28]:
            pixels[y][x] = pixels[y][x + 1] = 1
    for x in [10, 21]:
        if pose in ['blink', 'sleep']:
            for dx in [-1, 0, 1]: pixels[15][x + dx] = 1
        elif pose == 'happy':
            for dx, dy in [(-1, 0), (0, -1), (1, 0)]: pixels[15 + dy][x + dx] = 1
        else:
            for dx in [0, 1]:
                for dy in [0, 1, 2]: pixels[13 + dy][x + dx] = 1
            pixels[13][x] = 4
    for x in [7, 23]:
        pixels[18][x] = pixels[18][x + 1] = 4
        pixels[19][x] = pixels[19][x + 1] = 4
    for x in [15, 16]: pixels[19][x] = 1
    if pose == 'happy':
        for x in [15, 16]: pixels[20][x] = 5
    return [p for row in pixels for p in row]


def main():
    root = Path(__file__).resolve().parents[1]
    lines = ['/* Generated by tools/make_character.py. SPDX-License-Identifier: Apache-2.0 */', '#include "pet_model.h"', '#include "epet_module.h"', '#include <stddef.h>']
    for pose in ['idle', 'blink', 'happy', 'sleep']:
        lines.append(f'static const uint8_t {pose}_px[1024] = {{')
        pixels = frame(pose)
        lines.extend('    ' + ','.join(map(str, pixels[i:i + 32])) + ',' for i in range(0, 1024, 32))
        lines.extend(['};', f'static const epet_frame_t {pose}_frame = {{32, 32, {pose}_px}};'])
    lines += ['''static const epet_key_t idle_keys[] = {{&idle_frame, 2200}, {&blink_frame, 160}};
static const epet_key_t happy_keys[] = {{&happy_frame, 450}, {&idle_frame, 160}, {&happy_frame, 450}};
static const epet_key_t sleep_keys[] = {{&sleep_frame, 1000}};
static const epet_key_t sad_keys[] = {{&blink_frame, 800}, {&idle_frame, 400}};
static const epet_pose_t poses[] = {
    {"idle", idle_keys, 2, true}, {"birth", happy_keys, 3, false},
    {"happy", happy_keys, 3, false}, {"sad", sad_keys, 2, true},
    {"sleep", sleep_keys, 1, true},
};
static const epet_growth_t stages[] = {{1, 350, NULL, 0}, {11, 375, NULL, 0}, {31, 400, NULL, 0}};
static const epet_species_t ember = {
    .name = "EMBER", .blurb = "A little warmth, always with you",
    .palette = {.c = {0, EPET_RGB(78, 45, 21), EPET_RGB(255, 180, 59), EPET_RGB(239, 145, 38), EPET_RGB(255, 241, 185), EPET_RGB(232, 108, 94)}},
    .poses = poses, .n_poses = 6, .scale = 3,
    .temper = {1, 1, 1, 1}, .stages = stages, .n_stages = 3,
};
static const epet_species_t *const roster[] = {&ember};
static const epet_module_t module = {.id = "sugarat", .name = "Sugarat Ember", .version = 1, .species = roster, .n_species = 1};
void pet_species_register(void)
{
    if (!epet_modules_find(module.id)) epet_modules_install(&module, NULL);
}''']
    (root / 'main/pet/pet_character.c').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
