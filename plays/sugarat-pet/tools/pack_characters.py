#!/usr/bin/env python3
"""Pack the six source atlases into anchored indexed-color RLE firmware frames."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

SIZE = 96


def frame(image, index):
    """Normalize the generated equal-cell grid onto one bottom-centered canvas."""
    x, y = index % 4, index // 4
    cell = image.crop((round(x * image.width / 4), round(y * image.height / 4),
                       round((x + 1) * image.width / 4), round((y + 1) * image.height / 4))).convert('RGBA')
    alpha = cell.getchannel('A').point(lambda value: 255 if value >= 160 else 0)
    pixels = alpha.load()
    visited = set()
    components = []
    for py in range(cell.height):
        for px in range(cell.width):
            if pixels[px, py] and (px, py) not in visited:
                todo = [(px, py)]; visited.add((px, py)); component = []
                while todo:
                    point = todo.pop(); component.append(point)
                    for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                        nx, ny = point[0] + dx, point[1] + dy
                        if 0 <= nx < cell.width and 0 <= ny < cell.height and pixels[nx, ny] and (nx, ny) not in visited:
                            visited.add((nx, ny)); todo.append((nx, ny))
                components.append(component)
    if not components:
        raise ValueError('Frame has no opaque character')
    largest = max(len(component) for component in components)
    for component in components:
        if len(component) < largest // 100:
            for point in component:
                pixels[point] = 0
    cell.putalpha(alpha)
    bounds = alpha.getbbox()
    content = cell.crop(bounds)
    scale = min((SIZE - 10) / content.width, (SIZE - 12) / content.height)
    content = content.resize((round(content.width * scale), round(content.height * scale)), Image.Resampling.LANCZOS)
    output = Image.new('RGBA', (SIZE, SIZE))
    bottom = SIZE - 5 - (8 if index == 13 else 0)
    output.alpha_composite(content, ((SIZE - content.width) // 2, bottom - content.height))
    return output


def rle(values):
    """Store each run as length/index bytes, with transparent index zero."""
    output = bytearray()
    index = 0
    while index < len(values):
        value = values[index]; count = 1
        while index + count < len(values) and values[index + count] == value and count < 255:
            count += 1
        output.extend((count, value)); index += count
    decoded = bytearray()
    for index in range(0, len(output), 2):
        decoded.extend([output[index + 1]] * output[index])
    if decoded != values:
        raise ValueError('Indexed frame round trip differs')
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    folder = root / 'assets/characters'
    manifest = json.loads((folder / 'manifest.json').read_text())
    code = ['/* Generated by tools/pack_characters.py. Original Sugarat artwork. */', '#include "pet_art.h"']
    records = []; previews = []
    for item in manifest['characters']:
        path = folder / item['file']
        if hashlib.sha256(path.read_bytes()).hexdigest() != item['sha256']:
            raise ValueError(f'Artwork digest differs: {path.name}')
        image = Image.open(path).convert('RGBA')
        frames = [frame(image, index) for index in range(16)]
        if len({picture.tobytes() for picture in frames}) != 16:
            raise ValueError(f"Repeated source poses: {path.name}")
        colors = Image.new('RGB', (SIZE * 4, SIZE * 4), '#fff4e0')
        for index, picture in enumerate(frames):
            colors.paste(picture.convert('RGB'), (index % 4 * SIZE, index // 4 * SIZE))
        palette_image = colors.quantize(colors=31, method=Image.Quantize.MEDIANCUT)
        palette = palette_image.getpalette()[:31 * 3]
        palette += [0] * (768 - len(palette))
        lookup = Image.new('P', (1, 1)); lookup.putpalette(palette)
        words = [0]
        for index in range(31):
            r, g, b = palette[index * 3:index * 3 + 3]
            words.append(((r & 248) << 8) | ((g & 252) << 3) | (b >> 3))
        code.append(f'static const uint16_t palette_{item["key"]}[32] = {{' + ','.join(hex(w) for w in words) + '};')
        references = []
        for index, picture in enumerate(frames):
            quantized = picture.convert('RGB').quantize(palette=lookup, dither=Image.Dither.NONE)
            mask = picture.getchannel('A').tobytes()
            values = bytes(color + 1 if alpha >= 128 else 0 for color, alpha in zip(quantized.tobytes(), mask))
            if max(values) >= 32:
                raise ValueError('Palette index out of range')
            encoded = rle(values)
            name = f'frame_{item["key"]}_{index}'
            code.append(f'static const uint8_t {name}[] = {{')
            code.extend('    ' + ','.join(str(b) for b in encoded[start:start + 32]) + ',' for start in range(0, len(encoded), 32))
            code.append('};'); references.append('{'+name+',sizeof('+name+')}')
        records.append('{palette_'+item['key']+', {'+','.join(references)+'}}')
        previews.append(frames[0])
    code.append('const pet_art_character_t pet_art_characters[6] = {' + ',\n'.join(records) + '};')
    output = '\n'.join(code) + '\n'
    target = root / 'main/pet/pet_art.c'
    if options.check:
        if target.read_text() != output:
            raise SystemExit('Character resources differ; run tools/pack_characters.py')
    else:
        target.write_text(output)
    print('PASS: six characters, 96 distinct anchored frames, palette validation and RLE round trips')


if __name__ == '__main__':
    main()
