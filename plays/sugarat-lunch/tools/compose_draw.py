"""Generate the one-shot draw jingle and the screen timing it follows."""

import math
from pathlib import Path
import struct
import wave

app = Path(__file__).resolve().parents[1] / "main"
sample_rate = 16000
frames_ms = (80, 145, 210, 280, 360, 455, 570, 700, 850, 1030)
speaker_lead_ms = 80
samples = [0.0] * (sample_rate * 1380 // 1000)


def note(start_ms, length_ms, frequency, gain, voice):
    """Mix a note with a short attack and a decaying tail."""
    start = start_ms * sample_rate // 1000
    length = length_ms * sample_rate // 1000
    for i in range(length):
        phase = 2 * math.pi * frequency * i / sample_rate
        attack = min(1, i / (sample_rate * 0.004))
        decay = (1 - i / length) ** 1.6
        samples[start + i] += gain * attack * decay * voice(phase)


def chip(phase):
    return 0.72 * math.sin(phase) + 0.21 * math.sin(phase * 3) + 0.07 * math.sin(phase * 5)


def bell(phase):
    return 0.85 * math.sin(phase) + 0.15 * math.sin(phase * 2)


for frame, pitch in zip(frames_ms, (520, 587, 520, 659, 587, 698, 659, 587, 523)):
    note(frame - speaker_lead_ms, 42, pitch, 6500, chip)

reveal = frames_ms[-1] - speaker_lead_ms
note(reveal, 145, 523.25, 6900, bell)
note(reveal + 55, 155, 659.25, 6100, bell)
note(reveal + 110, 250, 783.99, 6200, bell)
note(reveal + 160, 240, 1046.5, 2700, bell)
assert max(map(abs, samples)) < 9000, "speaker headroom"

with wave.open(str(app / "audio" / "draw.wav"), "wb") as sound:
    sound.setparams((1, 2, sample_rate, 0, "NONE", "not compressed"))
    sound.writeframes(struct.pack(f"<{len(samples)}h", *map(round, samples)))

timing = ", ".join(map(str, frames_ms))
(app / "apps" / "draw_timing.h").write_text(
    "// SPDX-License-Identifier: Apache-2.0\n"
    "// Generated by tools/compose_draw.py for the embedded draw jingle.\n"
    f"static const uint16_t frame_ms[] = {{ {timing} }};\n",
    encoding="utf-8",
)
