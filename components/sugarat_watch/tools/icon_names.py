def enum_header(prefix, guard, doc):
    """Return a C header declaring the <prefix>_icon_t enum."""
    lower = prefix.lower()
    lines = ["/* SPDX-License-Identifier: Apache-2.0 */", f"/* Generated by tools/make_icons.py; do not edit. */",
             f"/** {doc} */", f"#ifndef {guard}", f"#define {guard}", "", "typedef enum {", f"    {prefix}_ICON_NONE,"]
    lines += [f"    {prefix}_ICON_{name}," for name, _ in ICONS]
    lines += [f"    {prefix}_ICON_COUNT,", f"}} {lower}_icon_t;", "", "#endif", ""]
    return "\n".join(lines)
