#!/usr/bin/env python3
"""Generate the Sugarat Watch icon fonts, sw_icons.h and sw_icon_glyphs.c from Font Awesome 5.

Writes include/sw_icons.h, src/sw_icon_glyphs.c and src/fonts/sw_font_icon_{16,20,28,40}.c.
Text fonts belong to tools/make_fonts.py. Requires Pillow and the LVGL 8.3
scripts/built_in_font directory, which holds FontAwesome5-Solid+Brands+Regular.woff.

usage: python3 tools/make_icons.py --font-dir <lvgl>/scripts/built_in_font
"""
from pathlib import Path
import argparse

from PIL import ImageFont

import make_fonts as fonts
from icon_names import ICONS, enum_header

WATCH = Path(__file__).resolve().parents[1]
FA = "FontAwesome5-Solid+Brands+Regular.woff"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--font-dir", type=Path, required=True)
    font_dir = parser.parse_args().font_dir
    (WATCH / "include/sw_icons.h").write_text(enum_header("SW", "SW_ICONS_H", "Icons shared with Sugarat Game; values index the icon glyph table."))
    rows = ["/* Generated by tools/make_icons.py; do not edit. */", '#include "sw_internal.h"', "",
            "const char *const sw_icon_glyphs[SW_ICON_COUNT] = {", '    "",']
    rows += ['    "' + "".join(f"\\x{b:02X}" for b in chr(cp).encode()) + f'", /* {n} */' for n, cp in ICONS]
    rows += ["};", ""]
    (WATCH / "src/sw_icon_glyphs.c").write_text("\n".join(rows))
    for size in (16, 20, 28, 40):
        big = ImageFont.truetype(str(font_dir / FA), size * fonts.SS)
        one = ImageFont.truetype(str(font_dir / FA), size)
        glyphs = []
        for _, cp in sorted(ICONS, key=lambda item: item[1]):
            g = fonts.render_aa(big, chr(cp), 0)
            if g is None:
                raise SystemExit(f"{FA} lacks U+{cp:04X}")
            glyphs.append((cp, round(one.getlength(chr(cp)) * 16), g))
        tops = [g[2][2] + g[2][0].height for g in glyphs]
        base = max(0, max(-g[2][2] for g in glyphs))
        name = f"sw_font_icon_{size}"
        n = fonts.write_font(WATCH / f"src/fonts/{name}.c", name, glyphs, 4, max(tops) + base, base, None,
                             "tools/make_icons.py")
        print(f"{name}: {len(glyphs)} glyphs, {n / 1024:.1f} KiB")


if __name__ == "__main__":
    main()
