def parse():
    art = {}
    for line in ART.strip().splitlines():
        name, *rows = line.split()
        if len(rows) != 8 or any(len(r) != 8 or set(r) - set(".#") for r in rows):
            raise SystemExit(f"{name}: expected 8 rows of 8 '.'/'#' cells")
        art[name] = [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]
    missing = [n for n, _ in ICONS if n not in art]
    if missing:
        raise SystemExit(f"missing pixel art: {missing}")
    return art


def main():
    art = parse()
    (OUT / "include/sg_icons.h").write_text(enum_header("SG", "SG_ICONS_H", "Icons shared with Sugarat Watch; values index the icon glyph table."))
    rows = ["/* Generated by tools/make_icons.py; do not edit. */", '#include "sg_internal.h"', "",
            "const char *const sg_icon_glyphs[SG_ICON_COUNT] = {", '    "",']
    rows += ['    "' + "".join(f"\\x{b:02X}" for b in chr(cp).encode()) + f'", /* {n} */' for n, cp in ICONS]
    rows += ["};", ""]
    (OUT / "src/sg_icon_glyphs.c").write_text("\n".join(rows))
    for scale in (2, 3, 4, 5):
        glyphs = []
        for name, cp in sorted(ICONS, key=lambda item: item[1]):
            image = Image.new("L", (8, 8), 0)
            for y, bits in enumerate(art[name]):
                for x in range(8):
                    if bits >> (7 - x) & 1:
                        image.putpixel((x, y), 255)
            image = image.resize((8 * scale, 8 * scale), Image.Resampling.NEAREST)
            glyphs.append((cp, 8 * scale * 16, (image, 0, 0)))
        name = f"sg_font_icon_{8 * scale}"
        n = fonts.write_font(OUT / f"src/fonts/{name}.c", name, glyphs, 1, 8 * scale, 0, None,
                             "tools/make_icons.py")
        print(f"{name}: {len(glyphs)} glyphs, {n / 1024:.1f} KiB")
    if len(sys.argv) > 1:
        from PIL import ImageDraw
        cols, cell = 12, 40
        sheet = Image.new("RGB", (cols * cell, (len(ICONS) + cols - 1) // cols * cell), (26, 28, 44))
        draw = ImageDraw.Draw(sheet)
        for i, (n, _) in enumerate(ICONS):
            x0, y0 = i % cols * cell + 4, i // cols * cell + 4
            for y, bits in enumerate(art[n]):
                for x in range(8):
                    if bits >> (7 - x) & 1:
                        draw.rectangle((x0 + x * 4, y0 + y * 4, x0 + x * 4 + 3, y0 + y * 4 + 3), fill=(255, 205, 117))
        sheet.save(sys.argv[1])


if __name__ == "__main__":
    main()
